#!/usr/bin/env bash
# Rebuild .claude/skills/ symlinks from scripts/skills-manifest.txt, pointing into
# vendor/skills/ (git submodules). Offline and idempotent — does not touch the
# network or move any submodule's checked-out commit. Run update-skills.sh for that.
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
vendor_dir="$root_dir/vendor/skills"
skills_dir="$root_dir/.claude/skills"
manifest="$root_dir/scripts/skills-manifest.txt"

mkdir -p "$skills_dir"

# Remove only symlinks we previously created (those pointing into vendor/skills/).
# Real directories (native project skills) and anything else are left alone.
for entry in "$skills_dir"/*; do
    [ -e "$entry" ] || continue
    if [ -L "$entry" ]; then
        target="$(readlink -f "$entry" || true)"
        case "$target" in
            "$vendor_dir"/*) rm "$entry" ;;
        esac
    fi
done

declare -A seen

while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"
    line="$(echo "$line" | xargs)"
    [ -z "$line" ] && continue

    skill_path="$vendor_dir/$line"
    skill_md="$skill_path/SKILL.md"

    if [ ! -f "$skill_md" ]; then
        echo "error: $skill_md not found (manifest entry: $line)" >&2
        exit 1
    fi

    name="$(awk -F': *' '/^name:[[:space:]]*/{print $2; exit}' "$skill_md" | tr -d '"'"'"'\r')"
    if [ -z "$name" ]; then
        echo "error: no 'name:' frontmatter field in $skill_md" >&2
        exit 1
    fi

    if [ -n "${seen[$name]+x}" ]; then
        echo "error: duplicate skill name '$name' from '$line' and '${seen[$name]}'" >&2
        exit 1
    fi
    seen[$name]="$line"

    link_path="$skills_dir/$name"
    if [ -e "$link_path" ] && [ ! -L "$link_path" ]; then
        echo "error: $link_path exists and is not a symlink, refusing to overwrite" >&2
        exit 1
    fi

    ln -sfnr "$skill_path" "$link_path"
    echo "linked $name -> vendor/skills/$line"
done < "$manifest"

# Keep a nested .gitignore in sync with the manifest so generated symlinks never
# get committed, while anything added by hand (native skills, not in the manifest)
# stays tracked normally.
{
    echo "# auto-generated by scripts/sync-skills.sh — do not edit by hand"
    for name in "${!seen[@]}"; do
        echo "$name"
    done | sort
} > "$skills_dir/.gitignore"
